GOLDEN = ROOT / "tests" / "fixtures" / "normalize_golden.jsonl"


def ranges_of(codepoints: List[int]) -> List[Tuple[int, int]]:
    out: List[Tuple[int, int]] = []
    for cp in sorted(codepoints):
        if out and cp == out[-1][1] + 1:
            out[-1] = (out[-1][0], cp)
        else:
            out.append((cp, cp))
    return out


def fmt_list(items: List[str], per_line: int = 6, indent: str = "    ") -> str:
    lines = []
    for i in range(0, len(items), per_line):
        lines.append(indent + ", ".join(items[i:i + per_line]) + ",")
    return "\n".join(lines)


def build_inc() -> str:
    compat = nr.compat_map()
    pool: List[int] = []
    entries: List[str] = []
    for cp in sorted(compat):
        s = compat[cp]
        entries.append("{0x%X,%d,%d}" % (cp, len(pool), len(s)))
        pool.extend(ord(c) for c in s)
    conf = nr.atr_confusables()
    for k, v in conf.items():
        if len(v) != 1:
            raise SystemExit(f"confusable {k:#x} maps to {v!r}: only single characters are supported")
    t = nr.trans_tables()
    spaces = ranges_of([cp for cp in range(0x110000) if not (0xD800 <= cp <= 0xDFFF) and chr(cp).isspace()])
    out = []
    out.append("// GENERATED by tools/gen_unicode_tables.py -- DO NOT EDIT.")
    out.append("// Unicode data: Python %s, unicodedata %s; sources: ATR src/engine.ts, trans-prompt-injection-detector." %
               (sys.version.split()[0], unicodedata.unidata_version))
    out.append("// Normalisation tables version %d. Changing the algorithm or the data requires a new version number," % nr.TABLES_VERSION)
    out.append("// because compiled rule sets depend on the exact normalised text.")
    out.append("#include <cstdint>")
    out.append("namespace apg { namespace tables {")
    out.append("static const uint32_t kTablesVersion = %d;" % nr.TABLES_VERSION)
    out.append('static const char kUnicodeVersion[] = "%s";' % unicodedata.unidata_version)
    out.append('static const char kTransPreprocessAstSha256[] = "%s";' % t["ast_sha256"])
    out.append("struct CompatEntry { uint32_t cp; uint32_t off; uint32_t len; };")
    out.append("struct Range { uint32_t lo; uint32_t hi; };")
    out.append("struct Pair { uint32_t from; uint32_t to; };")
    out.append("// NFKC of a single code point (only where it differs), sorted by cp; targets live in kCompatPool.")
    out.append("static const CompatEntry kCompat[] = {")
    out.append(fmt_list(entries, 6))
    out.append("};")
    out.append("static const uint32_t kCompatCount = %d;" % len(entries))
    out.append("static const uint32_t kCompatPool[] = {")
    out.append(fmt_list(["0x%X" % c for c in pool], 10))
    out.append("};")
    out.append("// Characters removed by fold_v1 (invisible / format / bidi / control).")
    out.append("static const Range kIgnorable[] = {")
    out.append(fmt_list(["{0x%X,0x%X}" % r for r in nr.IGNORABLE_RANGES], 6))
    out.append("};")
    out.append("static const uint32_t kIgnorableCount = %d;" % len(nr.IGNORABLE_RANGES))
    out.append("// ATR CONFUSABLE_TO_LATIN (Cyrillic / Greek look-alikes), sorted by 'from'.")
    out.append("static const Pair kAtrConfusables[] = {")
    out.append(fmt_list(["{0x%X,0x%X}" % (k, ord(v)) for k, v in sorted(conf.items())], 6))
    out.append("};")
    out.append("static const uint32_t kAtrConfusableCount = %d;" % len(conf))
    out.append("// trans_v1 (translation detector preprocessing).")
    out.append("static const Pair kTransHomoglyphs[] = {")
    out.append(fmt_list(["{0x%X,0x%X}" % (k, v) for k, v in sorted(t["homoglyph"].items())], 6))
    out.append("};")
    out.append("static const uint32_t kTransHomoglyphCount = %d;" % len(t["homoglyph"]))
    out.append("static const uint32_t kTransZeroWidth[] = {")
    out.append(fmt_list(["0x%X" % c for c in t["zero_width"]], 10))
    out.append("};")
    out.append("static const uint32_t kTransZeroWidthCount = %d;" % len(t["zero_width"]))
    out.append("static const Pair kTransPunct[] = {")
    out.append(fmt_list(["{0x%X,0x%X}" % (k, v) for k, v in sorted(t["punct"].items())], 6))
    out.append("};")
    out.append("static const uint32_t kTransPunctCount = %d;" % len(t["punct"]))
    out.append("// Python str.isspace() (what str.strip() removes), as ranges.")
    out.append("static const Range kPySpace[] = {")
    out.append(fmt_list(["{0x%X,0x%X}" % r for r in spaces], 6))
    out.append("};")
    out.append("static const uint32_t kPySpaceCount = %d;" % len(spaces))
    out.append("} }  // namespace apg::tables")
    return "\n".join(out) + "\n"


