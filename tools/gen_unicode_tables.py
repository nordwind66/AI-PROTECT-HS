def build_golden() -> str:
    lines = []
    for i, text in enumerate(GOLDEN_INPUTS):
        row = {"id": i, "input": text}
        for name, fn in (("raw", nr.raw), ("fold_v1", nr.fold_v1), ("trans_v1", nr.trans_v1)):
            out, offs = fn(text)
            row[name] = out
            row[name + "_offsets"] = offs
        lines.append(json.dumps(row, ensure_ascii=False, sort_keys=True))
    return "\n".join(lines) + "\n"


def main() -> int:
    setup_console()
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="only verify that the committed files are up to date")
    args = ap.parse_args()
    inc, golden = build_inc(), build_golden()
    if args.check:
        stale = []
        for path, text in ((INC, inc), (GOLDEN, golden)):
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path))
        if stale:
            print("STALE:", ", ".join(stale))
            return 1
        print("normalisation tables and golden vectors are up to date")
        return 0
    atomic_write_text(INC, inc)
    GOLDEN.parent.mkdir(parents=True, exist_ok=True)
    atomic_write_text(GOLDEN, golden)
    print(f"wrote {INC} ({len(inc) // 1024} KiB) and {GOLDEN} ({len(GOLDEN_INPUTS)} vectors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
