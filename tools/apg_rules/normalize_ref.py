# --- fold_v1 ---------------------------------------------------------------------------------------
IGNORABLE_RANGES: List[Tuple[int, int]] = [
    (0x0000, 0x0008), (0x000B, 0x000C), (0x000E, 0x001F), (0x007F, 0x0084), (0x0086, 0x009F),
    (0x00AD, 0x00AD), (0x034F, 0x034F), (0x061C, 0x061C), (0x115F, 0x1160), (0x17B4, 0x17B5),
    (0x180B, 0x180F), (0x200B, 0x200F), (0x202A, 0x202E), (0x2060, 0x2064), (0x2066, 0x206F),
    (0x3164, 0x3164), (0xFE00, 0xFE0F), (0xFEFF, 0xFEFF), (0xFFA0, 0xFFA0), (0xFFF9, 0xFFFB),
    (0x1BCA0, 0x1BCA3), (0x1D173, 0x1D17A), (0xE0000, 0xE007F), (0xE0100, 0xE01EF),
]

_ATR_ENGINE = Path(__file__).resolve().parent.parent.parent / "third_party" / "sources" / "agent-threat-rules" / "src" / "engine.ts"


def is_ignorable(cp: int) -> bool:
    for lo, hi in IGNORABLE_RANGES:
        if lo <= cp <= hi:
            return True
    return False


@lru_cache(maxsize=1)
def compat_map() -> Dict[int, str]:
    """cp -> NFKC(chr(cp)) for every code point whose NFKC form differs from itself."""
    table: Dict[int, str] = {}
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        n = unicodedata.normalize("NFKC", ch)
        if n != ch:
            table[cp] = n
    return table


@lru_cache(maxsize=1)
def atr_confusables() -> Dict[int, str]:
    """CONFUSABLE_TO_LATIN of the ATR reference engine, parsed (not executed) from src/engine.ts."""
    text = _ATR_ENGINE.read_text(encoding="utf-8")
    start = text.index("CONFUSABLE_TO_LATIN")
    end = text.index("};", start)
    block = text[start:end]
    pairs = re.findall(r"'\\u([0-9A-Fa-f]{4})'\s*:\s*'([^']+)'", block)
    if len(pairs) < 40:
        raise RuntimeError("could not parse CONFUSABLE_TO_LATIN from ATR engine.ts")
    return {int(h, 16): v for h, v in pairs}


def _trans_prep() -> Dict:
    import ast
    from sources import trans_pid  # tools/sources
    root = Path(__file__).resolve().parent.parent.parent / "third_party" / "sources" / "trans-prompt-injection-detector"
    tree, _ = trans_pid._load_tree(root)
    return trans_pid.extract_preprocess(tree)


@lru_cache(maxsize=1)
def trans_tables() -> Dict:
    prep = _trans_prep()
    punct = {a: b for a, b in prep["replaces"]
             if len(a) == 1 and a not in ("\n", "\t", "\r", " ") and len(b) == 1}
    return {
        "homoglyph": {ord(k): ord(v) for k, v in prep["homoglyphs"].items() if len(v) == 1},
        "zero_width": sorted(ord(c) for c in prep["zero_width"]),
        "punct": {ord(a): ord(b) for a, b in punct.items()},
        "ast_sha256": prep["ast_sha256"],
    }


def _utf8_len(ch: str) -> int:
    return len(ch.encode("utf-8"))


class _Out:
    """Output builder that records, for each output byte, the original byte offset."""

    def __init__(self) -> None:
        self.chars: List[str] = []
        self.src: List[int] = []          # per output CHARACTER: source byte offset

    def add(self, ch: str, src_off: int) -> None:
        self.chars.append(ch)
        self.src.append(src_off)

    def finish(self, total_src_bytes: int) -> Tuple[str, List[int]]:
        text = "".join(self.chars)
        offsets: List[int] = []
        for ch, off in zip(self.chars, self.src):
            offsets.extend([off] * _utf8_len(ch))
        offsets.append(total_src_bytes)
        return text, offsets


def raw(text: str) -> Tuple[str, List[int]]:
    offs: List[int] = []
    pos = 0
    for ch in text:
        n = _utf8_len(ch)
        offs.extend([pos] * n)
        pos += n
    offs.append(pos)
    return text, offs


def fold_v1(text: str) -> Tuple[str, List[int]]:
    compat = compat_map()
    conf = atr_confusables()
    out = _Out()
    pos = 0
    for ch in text:
        cp = ord(ch)
        n = _utf8_len(ch)
        if not is_ignorable(cp):
            seq = compat.get(cp, ch)
            for c2 in seq:
                cp2 = ord(c2)
                if is_ignorable(cp2):
                    continue
                m = conf.get(cp2)
                out.add(m if m is not None else c2, pos)
        pos += n
    return out.finish(pos)


def _py_strip_indices(chars: List[str]) -> Tuple[int, int]:
    lo, hi = 0, len(chars)
    while lo < hi and chars[lo].isspace():
        lo += 1
    while hi > lo and chars[hi - 1].isspace():
        hi -= 1
    return lo, hi


def trans_v1(text: str) -> Tuple[str, List[int]]:
    """Exact sequence of upstream preprocess_text (minus lower()). Offsets tracked per character."""
    t = trans_tables()
    zero = set(t["zero_width"])
    homog = t["homoglyph"]
    punct = t["punct"]
    chars: List[str] = []
    offs: List[int] = []
    pos = 0
    for ch in text:
        chars.append(ch)
        offs.append(pos)
        pos += _utf8_len(ch)
    total = pos
    # 1. strip
    lo, hi = _py_strip_indices(chars)
    chars, offs = chars[lo:hi], offs[lo:hi]
    # 2. zero-width removal
    keep = [i for i, c in enumerate(chars) if ord(c) not in zero]
    chars, offs = [chars[i] for i in keep], [offs[i] for i in keep]
    # 3. homoglyph translate
    chars = [chr(homog[ord(c)]) if ord(c) in homog else c for c in chars]
    # 4. \n \t \r -> space
    chars = [" " if c in ("\n", "\t", "\r") else c for c in chars]
    # 5. collapse runs of ASCII spaces (while "  " in text: replace("  ", " "))
    c2: List[str] = []
    o2: List[int] = []
    for c, o in zip(chars, offs):
        if c == " " and c2 and c2[-1] == " ":
            continue
        c2.append(c)
        o2.append(o)
    chars, offs = c2, o2
    # 6. drop characters below 0x20
    keep = [i for i, c in enumerate(chars) if ord(c) >= 32]
    chars, offs = [chars[i] for i in keep], [offs[i] for i in keep]
    # 7. CJK punctuation -> ASCII
    chars = [chr(punct[ord(c)]) if ord(c) in punct else c for c in chars]
    # (lower() omitted on purpose)  8. final strip
    lo, hi = _py_strip_indices(chars)
    chars, offs = chars[lo:hi], offs[lo:hi]
    out = _Out()
    for c, o in zip(chars, offs):
        out.add(c, o)
    return out.finish(total)


def _is_cjk(cp: int) -> bool:
    return (0x3400 <= cp <= 0x4DBF or 0x4E00 <= cp <= 0x9FFF or 0xF900 <= cp <= 0xFAFF
            or 0x20000 <= cp <= 0x2FFFF or 0x3040 <= cp <= 0x30FF)


DECOR_SEPS = set(" \t.-_*|/~`'\"+^#") | {"\u00b7", "\u2022", "\u30fb"}
SPELL_SEPS = set(" .-_*")
LEET = {"0": "o", "3": "e", "4": "a", "5": "s", "7": "t", "@": "a", "$": "s"}


def _is_letter(ch: str) -> bool:
    return "a" <= ch.lower() <= "z" and ch.isascii()


def _is_alnum(ch: str) -> bool:
    return _is_letter(ch) or "0" <= ch <= "9"


def deobf_v1(text: str) -> Tuple[str, List[int]]:
    folded, foffs = fold_v1(text)
    v: List[Tuple[str, int]] = []
    pos = 0
    for ch in folded:
        v.append((ch, foffs[pos]))
        pos += _utf8_len(ch)
    # 2. separators between two CJK characters
    a: List[Tuple[str, int]] = []
    i = 0
    while i < len(v):
        if v[i][0] not in DECOR_SEPS:
            a.append(v[i])
            i += 1
            continue
        j = i
        while j < len(v) and v[j][0] in DECOR_SEPS:
            j += 1
        if not (a and _is_cjk(ord(a[-1][0])) and j < len(v) and _is_cjk(ord(v[j][0]))):
            a.extend(v[i:j])
        i = j
    # 3. a word spelled out letter by letter
    b: List[Tuple[str, int]] = []
    i = 0
    while i < len(a):
        if _is_letter(a[i][0]) and (i == 0 or not _is_alnum(a[i - 1][0])):
            end, count = i, 1
            sep = a[i + 1][0] if i + 1 < len(a) else ""
            while (end + 2 < len(a) and sep in SPELL_SEPS and a[end + 1][0] == sep and _is_letter(a[end + 2][0])
                   and (end + 3 >= len(a) or not _is_alnum(a[end + 3][0]))):
                end += 2
                count += 1
            if count >= 3:
                b.extend(a[k] for k in range(i, end + 1, 2))
                i = end + 1
                continue
        b.append(a[i])
        i += 1
    # 4. leetspeak inside a word
    c: List[Tuple[str, int]] = []
    i = 0
    while i < len(b):
        if not (_is_alnum(b[i][0]) or b[i][0] in "@$"):
            c.append(b[i])
            i += 1
            continue
        j, letters, leet = i, 0, False
        while j < len(b) and (_is_alnum(b[j][0]) or b[j][0] in "@$"):
            ch = b[j][0]
            if _is_letter(ch):
                letters += 1
            elif ch == "1" or ch in LEET:
                leet = True
            j += 1
        if letters >= 1 and j - i >= 3 and leet:
            k = i
            while k < j:
                ch, off = b[k]
                if ch == "1":
                    r = k
                    while r < j and b[r][0] == "1":
                        r += 1
                    rep = "l" if r - k >= 2 else "i"
                    c.extend((rep, b[m][1]) for m in range(k, r))
                    k = r
                else:
                    c.append((LEET.get(ch, ch), off))
                    k += 1
        else:
            c.extend(b[i:j])
        i = j
    out = _Out()
    for ch, off in c:
        out.add(ch, off)
    return out.finish(len(text.encode("utf-8")))


